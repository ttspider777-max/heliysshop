QUESTION_START = ("как", "где", "что", "почему", "зачем", "можно", "сколько", "куда", "когда", "какой", "какая",
                  "подскаж", "помогит", "помоги", "не могу", "не получается", "не работает", "не отвечает", "кто")


def norm(text):
    return re.sub(r"\s+", " ", re.sub(r"[^\w\s?]", " ", (text or "").lower().replace("ё", "е"))).strip()


def is_question(text):
    t = norm(text)
    return "?" in (text or "") or t.startswith(QUESTION_START)


def entries():
    """Справочник + вопросы из /admin → ❓ FAQ (для FAQ основы слов берутся из самого вопроса)."""
    out = list(HELP)
    for f in core.jget("faq", core.FAQ):
        words = [w[:6] for w in norm(f.get("q")).split() if len(w) > 3]
        if words:
            out.append({"q": f.get("q") or "", "a": html.escape(f.get("a") or ""), "kw": words})
    return out


# общие глаголы («добавить», «сделать»…) весят меньше: «как добавить категорию» — про категории, а не про товары
GENERIC = ("добав", "созда", "нов", "измен", "сдела", "поменя", "убра")


def find_answer(text):
    """Лучший ответ из справочника или None."""
    t = " " + norm(text) + " "
    words = t.split()
    best, best_score = None, 0
    for e in entries():
        score = sum(0.5 if k in GENERIC else 1 for k in e["kw"] if (" " + k) in t)
        if any(s in t for s in e.get("strong", ())):
            score += 2
        if score > best_score:
            best, best_score = e, score
    if best is None:
        return None
    if best_score >= 2 or (best_score >= 1 and len(words) <= 6):
        return best
    return None


def answer_text(e):
    bot = core.get("username") or "бот-конструктор"
    return f"💡 <b>{html.escape(e['q'])}</b>\n\n" + e["a"].replace("{bot}", html.escape(bot))


# ======================= чаты =======================
def remember(chat):
    db.x("INSERT INTO ctor_groups(chat_id, title, added, active) VALUES (?, ?, ?, 1) ON CONFLICT(chat_id) DO UPDATE "
         "SET title=excluded.title, active=1", (chat.id, chat.title or "", db.now()))


def active_groups():
    return db.q("SELECT * FROM ctor_groups WHERE active=1 ORDER BY added")


@router.my_chat_member(F.chat.type.in_(GROUP))
async def on_added(ev: ChatMemberUpdated, bot: Bot):
    st = ev.new_chat_member.status
    if st in ("member", "administrator"):
        remember(ev.chat)
        if ev.old_chat_member.status in ("left", "kicked"):
            try:
                await bot.send_message(ev.chat.id, core.tx("group_hello", bot=html.escape(core.get("username") or "")))
            except Exception as e:
                log.info("конструктор: не поздоровался в чате %s: %s", ev.chat.id, e)
    else:
        db.x("UPDATE ctor_groups SET active=0 WHERE chat_id=?", (ev.chat.id,))


_last = {}  # (чат, вопрос) -> время ответа: не повторять один и тот же ответ чаще раза в 2 минуты


@router.message(F.chat.type.in_(GROUP), F.text)
async def on_group_text(m: Message, bot: Bot):
    remember(m.chat)
    if not core.flag_on("group_help") or not m.from_user or m.from_user.is_bot:
        return
    if m.from_user.id in config.ADMINS:  # на вопросы владельца не отвечаю — он сам отвечает людям
        return
    me = core.get("username") or ""
    to_me = bool(me) and f"@{me.lower()}" in m.text.lower()
    if m.reply_to_message and not (m.reply_to_message.from_user and m.reply_to_message.from_user.id == bot.id):
        if not to_me:
            return  # люди переписываются между собой
    if not (to_me or is_question(m.text)):
        return
    e = find_answer(m.text)
    if not e:
        return
    key = (m.chat.id, e["q"])
    now = time.monotonic()
    if now - _last.get(key, -1e9) < 120:
        return
    _last[key] = now
    rows = []
    if me:
        rows.append([raw_btn(f"🤖 Открыть @{me}", url=f"https://t.me/{me}")])
    await m.reply(answer_text(e), reply_markup=kb(rows) if rows else None)


# ======================= напоминания в чаты =======================
def mention(u, uid):
    """Упоминание владельца в чате (без ID — его видно только в админке)."""
    name = html.escape((u["first_name"] if u else None) or "владелец")
    tail = f" (@{u['username']})" if u and u["username"] else ""
    return f'<a href="tg://user?id={uid}">{name}</a>{html.escape(tail)}'


async def remind_in_groups(bot: Bot, uid, text):
    """Напоминание владельцу магазина во все чаты с конструктором, где он состоит. -> сколько отправлено."""
    if not core.flag_on("remind_groups"):
        return 0
    u = core.user(uid)
    sent = 0
    for g in active_groups():
        try:
            mem = await bot.get_chat_member(g["chat_id"], uid)
        except Exception as e:
            log.info("конструктор: чат %s недоступен: %s", g["chat_id"], e)
            continue
        if mem.status not in ("member", "administrator", "creator", "restricted"):
            continue
        me = core.get("username") or ""
        markup = kb([[raw_btn("💳 Продлить в боте", url=f"https://t.me/{me}")]]) if me else None
        try:
            await bot.send_message(g["chat_id"], f"👤 {mention(u, uid)}\n" + text, reply_markup=markup)
            sent += 1
        except Exception as e:
            log.info("конструктор: не отправил напоминание в чат %s: %s", g["chat_id"], e)
    return sent
